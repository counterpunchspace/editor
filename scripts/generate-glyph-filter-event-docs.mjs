#!/usr/bin/env node

/**
 * Glyph Filter Event Documentation Generator
 *
 * Transpiles the typed registry in memory and renders its public contract.
 *
 * Usage:
 *   node scripts/generate-glyph-filter-event-docs.mjs
 */

import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join, relative } from 'path';
import ts from 'typescript';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const REPO_ROOT = join(__dirname, '..');
const REGISTRY_PATH = join(REPO_ROOT, 'webapp', 'js', 'glyph-filter-events.ts');
const OUTPUT_PATH = join(
    REPO_ROOT,
    'developer-docs',
    'GLYPH_FILTER_EVENTS.md'
);

/** Loads the TypeScript-only registry without requiring a separate build step. */
async function loadRegistry() {
    const source = readFileSync(REGISTRY_PATH, 'utf-8');
    const output = ts.transpileModule(source, {
        compilerOptions: {
            module: ts.ModuleKind.ESNext,
            target: ts.ScriptTarget.ES2021
        },
        fileName: REGISTRY_PATH
    }).outputText;
    const encoded = Buffer.from(output).toString('base64');
    return import(`data:text/javascript;base64,${encoded}`);
}

function renderMarkdown(eventTypes, registry) {
    const lines = [
        '# Glyph Filter Event Reference',
        '',
        '> Generated by `node scripts/generate-glyph-filter-event-docs.mjs`. Do not edit this file by hand.',
        '',
        'This document lists the glyph-content events simple glyph filters may subscribe to. Feature generators subscribe to the same event names.',
        '',
        '## Simple Filter Contract',
        '',
        'A filter requires literal `EVENT_TYPES` and `classify_glyph(glyph)`. It may define a cheap `is_candidate(glyph)` gate. The host owns glyph creation, deletion, renaming, cache replacement, and group cleanup.',
        '',
        '```python',
        'EVENT_TYPES = ["glyph.anchors.changed"]',
        '',
        'def classify_glyph(glyph):',
        '    return not glyph.anchors',
        '```',
        '',
        'Return `False` to hide a glyph or `True` to show it without groups. Return a mapping with groups only when categories are needed. Do not use lifecycle events in `EVENT_TYPES`: `glyph.created`, `glyph.deleted`, and `glyph.renamed` are always handled by the host. Do not use `font.masters.changed` in a simple filter. Every returned group is a complete `{name, color}` mapping; group names identify groups and colors are last-wins.',
        '',
        '## Events',
        ''
    ];

    for (const type of eventTypes) {
        const event = registry[type];
        lines.push(`## \`${type}\``);
        lines.push('');
        lines.push(`- Name: ${event.name}`);
        lines.push(`- Description: ${event.description}`);
        lines.push('');
        lines.push('### Metadata');
        lines.push('');
        lines.push('| Field | Type | Required | Description |');
        lines.push('| --- | --- | --- | --- |');
        for (const field of event.metadataFields) {
            lines.push(
                `| \`${field.name}\` | \`${field.type}\` | ${field.required ? 'Yes' : 'No'} | ${field.description} |`
            );
        }
        lines.push('');
    }

    return `${lines.join('\n')}\n`;
}

async function main() {
    const { GLYPH_FILTER_EVENT_REGISTRY, GLYPH_FILTER_EVENT_TYPES } =
        await loadRegistry();
    writeFileSync(
        OUTPUT_PATH,
        renderMarkdown(GLYPH_FILTER_EVENT_TYPES, GLYPH_FILTER_EVENT_REGISTRY),
        'utf-8'
    );
    console.log(
        `Generated ${GLYPH_FILTER_EVENT_TYPES.length} glyph filter event reference entries at ${relative(REPO_ROOT, OUTPUT_PATH)}`
    );
}

main();
