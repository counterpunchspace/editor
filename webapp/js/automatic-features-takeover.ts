/**
 * Shared UI for "Counterpunch manages automatic features": the outcome
 * preview used by Convert to Counterpunch and the Features panel switch.
 */

import { attachOutcomePreviewTippy } from './tippy-utils';
import { highlightFeaSource } from './delete-glyphs-dialog';
import { bindModalEscape } from './ui/modal-escape';
import {
    featureGeneratorEngine,
    type TakeoverPreview
} from './language-packs/feature-generator-engine';
import type { FeatureBlockSummary } from './language-packs/managed-features';

export function escapeHtml(value: string): string {
    return value
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;');
}

function blockTitle(block: FeatureBlockSummary): string {
    if (block.kind === 'class') {
        return `@${block.name}`;
    }
    if (block.kind === 'prefix') {
        return `prefix ${block.name}`;
    }
    return block.name;
}

function blockHtml(block: FeatureBlockSummary): string {
    const lines = block.code
        .split('\n')
        .map(
            (line, index) => `<div class="delete-glyphs-fea-line">
                <span class="delete-glyphs-fea-line-number">${index + 1}</span>
                <code class="delete-glyphs-fea-code">${highlightFeaSource(line)}</code>
            </div>`
        )
        .join('');
    return `<section class="delete-glyphs-fea-block">
        <header class="delete-glyphs-preview-heading">${escapeHtml(blockTitle(block))}</header>
        <div class="delete-glyphs-fea-lines">${lines}</div>
    </section>`;
}

/** Counts and one-line summary used by the option row. */
export function takeoverCounts(preview: TakeoverPreview): {
    removed: number;
    kept: number;
    generated: number;
    summary: string;
} {
    const removed = preview.removed.length;
    const kept = preview.kept.length;
    const generated = preview.generated.length;
    const parts = [`remove ${removed}`];
    if (kept) {
        parts.push(`keep ${kept} still in use`);
    }
    parts.push(`generate ${generated}`);
    return { removed, kept, generated, summary: parts.join(', ') };
}

export function buildTakeoverPreviewHtml(preview: TakeoverPreview): string {
    const removed = preview.removed.length
        ? preview.removed
              .map(
                  (block) =>
                      `${blockHtml(block)}${
                          block.stamped
                              ? ''
                              : '<p class="delete-glyphs-preview-legend">Not generated by Counterpunch. It will not come back unless a generator writes it.</p>'
                      }`
              )
              .join('')
        : '<div class="delete-glyphs-preview-empty">No automatic blocks</div>';
    const generated = preview.generated.length
        ? preview.generated.map(blockHtml).join('')
        : '<div class="delete-glyphs-preview-empty">Nothing generated</div>';
    const kept = preview.kept.length
        ? `<p class="delete-glyphs-preview-legend">Kept: marked automatic, but other feature code uses them and Counterpunch does not generate them (${preview.kept.length}).</p>
        ${preview.kept.map(blockHtml).join('')}`
        : '';
    return `<div class="delete-glyphs-preview delete-glyphs-fea-preview">
        <p class="delete-glyphs-preview-legend">Removed: blocks marked automatic (${preview.removed.length}).</p>
        ${removed}
        ${kept}
        <p class="delete-glyphs-preview-legend">Generated by Counterpunch (${preview.generated.length}).</p>
        ${generated}
    </div>`;
}

/** Features panel: confirm replacing automatic blocks before switching on. */
export async function confirmAutomaticFeaturesTakeover(): Promise<boolean> {
    await featureGeneratorEngine.ensureReady();
    const preview = featureGeneratorEngine.previewTakeover();
    if (!preview) {
        return false;
    }
    return new Promise((resolve) => {
        const overlay = document.createElement('div');
        overlay.className = 'info-popup-overlay';
        overlay.style.display = 'flex';
        overlay.style.zIndex = '10002';
        const counts = takeoverCounts(preview);
        overlay.innerHTML = `
            <div class="info-popup confirm-dialog">
                <div class="info-popup-header">
                    <h3>Counterpunch manages automatic features</h3>
                    <button type="button" class="info-popup-close confirm-dialog-close-btn" aria-label="Cancel">
                        <span class="material-symbols-outlined">close</span>
                    </button>
                </div>
                <div class="info-popup-content confirm-dialog-content">
                    <p>All features marked automatic are removed and replaced with the features Counterpunch generates. From then on they update after glyph operations. This can be undone.</p>
                    <div class="confirm-dialog-options">
                        <ul class="confirm-dialog-report">
                            <li class="confirm-dialog-report-item">
                                <span>${escapeHtml(counts.summary.charAt(0).toUpperCase() + counts.summary.slice(1))}</span>
                                <button type="button" class="confirm-dialog-info-btn material-symbols-outlined" aria-label="Preview">info</button>
                            </li>
                        </ul>
                    </div>
                    <div class="confirm-dialog-actions">
                        <button type="button" class="dialog-button" data-action="cancel">Cancel</button>
                        <button type="button" class="dialog-button dialog-button-primary" data-action="confirm">Replace</button>
                    </div>
                </div>
            </div>
        `;
        document.body.appendChild(overlay);
        const tip = attachOutcomePreviewTippy(
            overlay.querySelector('.confirm-dialog-info-btn') as HTMLElement,
            buildTakeoverPreviewHtml(preview)
        );
        let escapeBinding: ReturnType<typeof bindModalEscape> | null = null;
        const finish = (confirmed: boolean) => {
            tip.destroy();
            escapeBinding?.release();
            escapeBinding = null;
            overlay.remove();
            resolve(confirmed);
        };
        escapeBinding = bindModalEscape(() => finish(false), {
            isOpen: () => overlay.isConnected
        });
        overlay.addEventListener('click', (event) => {
            if (event.target === overlay) {
                finish(false);
            }
        });
        overlay
            .querySelector('.confirm-dialog-close-btn')
            ?.addEventListener('click', () => finish(false));
        overlay
            .querySelector('[data-action="cancel"]')
            ?.addEventListener('click', () => finish(false));
        overlay
            .querySelector('[data-action="confirm"]')
            ?.addEventListener('click', () => finish(true));
    });
}

/** Switch on in one undo step: set the flag and replace automatic blocks. */
export function enableAutomaticFeatures(label: string): boolean {
    const font = window.currentFontModel;
    const bridge = window.patchSyncEngine;
    if (!font) {
        return false;
    }
    bridge?.beginTransaction(label, null, {
        compileChangeSource: 'feature-code',
        compileEditType: null
    });
    try {
        font.setCounterpunchManagesFeatures(true);
        return featureGeneratorEngine.applyTakeover();
    } finally {
        bridge?.endTransaction();
    }
}
