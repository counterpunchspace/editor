#!/usr/bin/env node
// Writes js/generated/axis-registry.ts from the Google Fonts axis registry,
// pinned to one upstream commit. Bump REGISTRY_COMMIT and rerun to update.
//
//   node scripts/generate-axis-registry.mjs

import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REGISTRY_COMMIT = 'a6f6f2fd43d30b6a2564cd85925e1d98c4871ab9';
const DATA_PATH = 'Lib/axisregistry/data';
const OUT = path.join(
    path.dirname(fileURLToPath(import.meta.url)),
    '../js/generated/axis-registry.ts'
);

async function getJson(url) {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${response.status} for ${url}`);
    return response.json();
}

async function getText(url) {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${response.status} for ${url}`);
    return response.text();
}

// The registry's textproto files are flat: scalar fields plus repeated
// `fallback { name: "…" value: … }` blocks. Trailing `#` comments are allowed.
function parseNumber(raw) {
    const value = Number(raw.split('#')[0].trim());
    if (!Number.isFinite(value)) throw new Error(`Not a number: ${raw}`);
    return value;
}

function parseAxis(text) {
    const field = (key) => {
        const match = text.match(new RegExp(`^${key}:\\s*"?([^"\\n]*)"?`, 'm'));
        if (!match) throw new Error(`Missing ${key}`);
        return match[1];
    };
    const fallbacks = [
        ...text.matchAll(
            /fallback\s*\{\s*name:\s*"([^"]*)"\s*value:\s*([-\d.]+)/g
        )
    ].map(([, name, value]) => [name, parseNumber(value)]);
    return {
        tag: field('tag'),
        name: field('display_name'),
        min: parseNumber(field('min_value')),
        default: parseNumber(field('default_value')),
        max: parseNumber(field('max_value')),
        fallbacks
    };
}

const listing = await getJson(
    `https://api.github.com/repos/googlefonts/axisregistry/contents/${DATA_PATH}?ref=${REGISTRY_COMMIT}`
);
const files = listing
    .map((entry) => entry.name)
    .filter((name) => name.endsWith('.textproto'))
    .sort();
const axes = [];
for (const file of files) {
    const text = await getText(
        `https://raw.githubusercontent.com/googlefonts/axisregistry/${REGISTRY_COMMIT}/${DATA_PATH}/${file}`
    );
    axes.push(parseAxis(text));
}
axes.sort((a, b) => a.tag.localeCompare(b.tag));

const body = `/**
 * GENERATED by scripts/generate-axis-registry.mjs from the Google Fonts axis
 * registry (github.com/googlefonts/axisregistry @ ${REGISTRY_COMMIT.slice(0, 12)}).
 * Do not edit by hand.
 *
 * Values are userspace. \`fallbacks\` are the registry's named style values.
 */

export type RegisteredAxis = {
    tag: string;
    name: string;
    min: number;
    default: number;
    max: number;
    fallbacks: ReadonlyArray<readonly [name: string, value: number]>;
};

export const AXIS_REGISTRY: ReadonlyArray<RegisteredAxis> = ${JSON.stringify(axes, null, 4)};
`;
await writeFile(OUT, body);
console.log(
    `Wrote ${axes.length} axes to ${path.relative(process.cwd(), OUT)}`
);
