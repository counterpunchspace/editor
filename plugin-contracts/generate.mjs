import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const contracts = JSON.parse(readFileSync(join(root, "contracts.json"), "utf8"));
const schema = readFileSync(join(root, "manifest.schema.json"), "utf8");
const sha256 = createHash("sha256")
  .update(readFileSync(join(root, "contracts.json")))
  .update(readFileSync(join(root, "manifest.schema.json")))
  .update(readFileSync(join(root, "preflight.py")))
  .digest("hex");

const ts = `/* Generated by plugin-contracts/generate.mjs. Do not edit. */
export const PLUGIN_CONTRACTS_SHA256 = ${JSON.stringify(sha256)};
export const PYODIDE_VERSION = ${JSON.stringify(contracts.pyodideVersion)};
export const PLUGIN_WHEEL_TAGS = ${JSON.stringify(contracts.wheelTags)} as const;
export const PLUGIN_ALLOWED_DEPENDENCIES = ${JSON.stringify(contracts.allowedDependencies)} as const;
export const PLUGIN_CONTRACTS = ${JSON.stringify(contracts, null, 2)} as const;
export const PLUGIN_MANIFEST_SCHEMA = ${schema.trim()} as const;

export function contractToken(type: string, version: number): string {
  return type + ":v" + version;
}

export function editorSupportsContract(type: string, token: string): boolean {
  const spec = PLUGIN_CONTRACTS.types.find((item) => item.type === type);
  if (!spec) return false;
  return spec.editorSupports.some((version) => contractToken(type, version) === token);
}
`;

const py = `# Generated by plugin-contracts/generate.mjs. Do not edit.
PLUGIN_CONTRACTS_SHA256 = ${JSON.stringify(sha256)}
PYODIDE_VERSION = ${JSON.stringify(contracts.pyodideVersion)}
PLUGIN_CONTRACTS_JSON = ${JSON.stringify(JSON.stringify(contracts))}
`;

const editorRoot = join(root, "..");
const tsPath = join(editorRoot, "webapp/js/plugin-contracts.generated.ts");
writeFileSync(tsPath, ts);
writeFileSync(join(editorRoot, "webapp/py/plugin_contracts_generated.py"), py);
const prettier = join(editorRoot, "webapp/node_modules/.bin/prettier");
const formatted = spawnSync(
  prettier,
  ["--ignore-path", join(editorRoot, "webapp/.prettierignore"), "--write", tsPath],
  { stdio: "inherit" }
);
if (formatted.status !== 0) {
  process.exit(formatted.status ?? 1);
}
writeFileSync(join(root, "contracts.sha256"), sha256 + "\n");
console.log(sha256);
